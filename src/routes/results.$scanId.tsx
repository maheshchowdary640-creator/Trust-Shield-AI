import { createFileRoute, Link } from "@tanstack/react-router";
import { useServerFn } from "@tanstack/react-start";
import { useQuery } from "@tanstack/react-query";
import { ArrowLeft } from "lucide-react";
import { AppShell } from "@/components/app-shell";
import { ErrorPanel, GlassCard } from "@/components/security-ui";
import { ScanResultView } from "@/components/scan-result-view";
import { getScan } from "@/lib/scans.functions";
import { SCAN_TYPE_LABELS } from "@/lib/scan-types";
import { AuthGuard } from "@/components/auth-guard";

export const Route = createFileRoute("/results/$scanId")({
  head: () => ({
    meta: [
      { title: "Scan Report — TrustShield AI" },
      {
        name: "description",
        content:
          "Full TrustShield AI report with trust score, risk level, detected signals and recommended action.",
      },
      { property: "og:title", content: "Scan Report — TrustShield AI" },
      {
        property: "og:description",
        content: "Detailed fraud analysis report generated by TrustShield AI.",
      },
      { property: "og:type", content: "article" },
      { name: "twitter:card", content: "summary_large_image" },
    ],
  }),
  component: () => (
    <AuthGuard>
      <ResultsPage />
    </AuthGuard>
  ),
});

function ResultsPage() {
  const { scanId } = Route.useParams();
  const fetchScan = useServerFn(getScan);
  const { data, isLoading, error } = useQuery({
    queryKey: ["scan", scanId],
    queryFn: () => fetchScan({ data: { id: scanId } }),
  });

  return (
    <AppShell>
      <Link
        to="/history"
        className="mb-5 inline-flex items-center gap-2 text-sm text-muted-foreground hover:text-foreground"
      >
        <ArrowLeft className="size-4" /> Back to history
      </Link>

      {error && (
        <ErrorPanel
          message={error instanceof Error ? error.message : "Could not load this report."}
        />
      )}

      {isLoading && (
        <div className="grid gap-5 lg:grid-cols-[320px_1fr]">
          <div className="h-80 animate-pulse rounded-2xl border border-glass-border bg-card/40" />
          <div className="h-80 animate-pulse rounded-2xl border border-glass-border bg-card/40" />
        </div>
      )}

      {!isLoading && !error && !data && (
        <GlassCard className="p-12 text-center text-sm text-muted-foreground">
          This report no longer exists.
        </GlassCard>
      )}

      {data && (
        <>
          <header className="mb-6">
            <p className="font-mono text-xs uppercase tracking-widest text-primary">
              {
                SCAN_TYPE_LABELS[
                  data.scan_type as "screenshot" | "job_offer" | "url" | "voice" | "deepfake"
                ]
              }
            </p>
            <h1 className="mt-1.5 break-words font-display text-3xl">{data.input_label}</h1>
          </header>
          <ScanResultView scan={data} showLink={false} />
          <GlassCard className="mt-5 p-6">
            <h3 className="font-display text-sm uppercase tracking-[0.18em] text-muted-foreground">
              Raw evidence
            </h3>
            <pre className="mt-4 max-h-96 overflow-auto rounded-xl border border-glass-border bg-background/60 p-4 font-mono text-xs text-muted-foreground">
              {JSON.stringify(data.details, null, 2)}
            </pre>
          </GlassCard>
        </>
      )}
    </AppShell>
  );
}
